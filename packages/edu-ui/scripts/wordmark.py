"""Draws the brand name as SVG outlines in Anybody, so the logo never depends on a web font.

The amber signal light is the dot of the first i, or, for a name without one (taksu), a full stop
after the name. Run it again after renaming the brand, then commit the regenerated file:

    python3 packages/edu-ui/scripts/wordmark.py taksu

Needs fontTools and brotli (pip install fonttools brotli) and `pnpm install` for the font.
"""

import glob
import os
import sys

from fontTools.pens.boundsPen import BoundsPen
from fontTools.pens.recordingPen import RecordingPen
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont

WIDTH = 125  # Anybody wdth axis, 50 to 150
WEIGHT = 850
ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..', '..'))
OUT = os.path.join(ROOT, 'packages', 'edu-ui', 'src', 'brand', 'wordmark-path.ts')


def find_font() -> str:
    pattern = os.path.join(
        ROOT, 'node_modules', '.pnpm', '@fontsource-variable+anybody@*', 'node_modules',
        '@fontsource-variable', 'anybody', 'files', 'anybody-latin-wdth-italic.woff2',
    )
    matches = sorted(glob.glob(pattern))
    if not matches:
        sys.exit('Anybody not found: run pnpm install first.')
    return matches[-1]


def contours(glyph_set, name):
    pen = RecordingPen()
    glyph_set[name].draw(pen)
    out, current = [], []
    for op, args in pen.value:
        current.append((op, args))
        if op in ('closePath', 'endPath'):
            out.append(current)
            current = []
    if current:
        out.append(current)
    return out


def replay(ops, pen):
    for op, args in ops:
        getattr(pen, op)(*args)


def main(name: str) -> None:
    font = instantiateVariableFont(TTFont(find_font()), {'wdth': WIDTH, 'wght': WEIGHT})
    glyphs = font.getGlyphSet()
    cmap = font.getBestCmap()
    x_height = font['OS/2'].sxHeight
    ascent = font['hhea'].ascent

    paths, x, dot = [], 0.0, None
    for char in name:
        glyph = cmap[ord(char)]
        for contour in contours(glyphs, glyph):
            bounds_pen = BoundsPen(glyphs)
            replay(contour, bounds_pen)
            bounds = bounds_pen.bounds
            if char == 'i' and bounds and bounds[1] > x_height * 0.9 and dot is None:
                dot = ((bounds[0] + bounds[2]) / 2 + x, (bounds[1] + bounds[3]) / 2, bounds[3] - bounds[1])
                continue
            svg_pen = SVGPathPen(glyphs, ntos=lambda n: f'{n:.0f}')
            replay(contour, TransformPen(svg_pen, (1, 0, 0, -1, x, 0)))
            paths.append(svg_pen.getCommands())
        x += glyphs[glyph].width

    if dot is None:
        # No i: the signal light becomes a full stop, sitting on the baseline after the name.
        bounds_pen = BoundsPen(glyphs)
        glyphs[cmap[ord('.')]].draw(bounds_pen)
        left, bottom, right, top_ = bounds_pen.bounds
        radius = (top_ - bottom) / 2 * 1.6
        cx, cy = x + left + radius, radius
        x = cx + radius
    else:
        cx, cy, height = dot
        radius = height / 2 * 1.6
    top = -max(ascent, cy + radius) - 20
    view_box = f'-30 {top:.0f} {x + 60:.0f} {-top + 30:.0f}'
    with open(OUT, 'w') as file:
        file.write(
            '// Generated by packages/edu-ui/scripts/wordmark.py. Do not edit by hand.\n\n'
            f'export const wordmarkName = {name!r};\n'
            f"export const wordmarkViewBox = '{view_box}';\n"
            f"export const wordmarkPath =\n  '{' '.join(paths)}';\n"
            f'export const wordmarkDot = {{ cx: {cx:.0f}, cy: {-cy:.0f}, r: {radius:.0f} }};\n'
        )
    print(f'wrote {OUT}')


if __name__ == '__main__':
    main(sys.argv[1] if len(sys.argv) > 1 else 'taksu')
